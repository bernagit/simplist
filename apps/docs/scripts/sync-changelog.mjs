// Publishes the full changelog (written by changesets in apps/app/CHANGELOG.md) as a docs page,
// in both locales. Runs before `astro dev` and `astro build`; the generated pages are gitignored.
// The app only shows the short, user-facing notes (apps/app/release-notes.json).
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const docsRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = path.resolve(docsRoot, '../app/CHANGELOG.md')
const contentDir = path.join(docsRoot, 'src/content/docs')

const pages = {
  it: {
    file: 'changelog.md',
    title: 'Changelog',
    description: 'Tutte le modifiche di ogni versione di Simplist, anche quelle tecniche.',
    intro:
      "Elenco completo delle modifiche, generato a ogni rilascio. Nell'app, dopo un aggiornamento, compare solo un riassunto delle novità. Il changelog è in inglese."
  },
  en: {
    file: 'en/changelog.md',
    title: 'Changelog',
    description: 'Every change in every Simplist version, technical ones included.',
    intro:
      'The complete list of changes, generated at every release. After an update the app only shows a short summary of what is new.'
  }
}

if (!fs.existsSync(source)) {
  console.warn(`[changelog] ${source} not found: skipping the changelog page`)
  process.exit(0)
}

const body = fs
  .readFileSync(source, 'utf8')
  // The package name heading ("# app"): the page has its own title
  .replace(/^# .*\n+/, '')
  // Old entries were written as "## v0.2.0"
  .replace(/^## v(\d)/gm, '## $1')

for (const page of Object.values(pages)) {
  const target = path.join(contentDir, page.file)
  const content = `---
title: ${page.title}
description: ${page.description}
---

<!-- Generated by scripts/sync-changelog.mjs from apps/app/CHANGELOG.md: do not edit -->

${page.intro}

${body}`
  fs.mkdirSync(path.dirname(target), { recursive: true })
  fs.writeFileSync(target, content)
}
console.log('[changelog] docs changelog page updated')
